#!/usr/bin/env node
/**
 * Regenerates docs/reference/github-actions-secrets.md from scripts/lib/setup-manifest.mjs.
 * Run: npm run docs:actions-secrets
 */

import { writeFileSync } from 'node:fs';
import path from 'node:path';
import url from 'node:url';

import { GITHUB_SECRETS, GITHUB_VARIABLES } from './lib/setup-manifest.mjs';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const OUT = path.join(REPO_ROOT, 'docs', 'reference', 'github-actions-secrets.md');

const lines = [];
lines.push('# GitHub Actions secrets and variables');
lines.push('');
lines.push(
  '<!-- AUTO-GENERATED by `npm run docs:actions-secrets` from `scripts/lib/setup-manifest.mjs` — do not edit by hand -->',
);
lines.push('');
lines.push(
  'This file lists repository **secrets** and **variables** the setup wizard can sync via `gh`. Names and optional flags are defined in [`scripts/lib/setup-manifest.mjs`](../../scripts/lib/setup-manifest.mjs).',
);
lines.push('');
lines.push('## Secrets');
lines.push('');
lines.push('| Name | Optional | Group |');
lines.push('| --- | --- | --- |');
for (const def of GITHUB_SECRETS) {
  lines.push(`| \`${def.name}\` | ${def.optional ? 'yes' : 'no'} | ${def.group || ''} |`);
}
lines.push('');
lines.push('## Variables');
lines.push('');
lines.push('| Name | Optional | Group |');
lines.push('| --- | --- | --- |');
for (const def of GITHUB_VARIABLES) {
  lines.push(`| \`${def.name}\` | ${def.optional ? 'yes' : 'no'} | ${def.group || ''} |`);
}
lines.push('');

writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`Wrote ${path.relative(REPO_ROOT, OUT)}`);
